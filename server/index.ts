// List all packs with light metadata for the dropdown
app.get('/api/songs', async (req, res) => {
  try {
    const { readdir, readFile } = await import('fs/promises');
    const dirs = await readdir(songsPath, { withFileTypes: true });
    const packs = [];
    for (const d of dirs) {
      if (!d.isDirectory()) continue;
      try {
        const raw = await readFile(join(songsPath, d.name, 'song.json'), 'utf8');
        const p = JSON.parse(raw);
        const autoGenerated = p.autoGenerated === true || p.sourceTrack?.name?.includes('auto');
        packs.push({ id: p.id, title: p.title, youtubeId: p.youtubeId, syncOffset: p.syncOffset || 0, duration: p.duration, noteCount: p.notes?.length || 0, autoGenerated });
      } catch { /* skip malformed pack */ }
    }
    packs.sort((a, b) => a.title.localeCompare(b.title));
    res.json({ songs: packs });
  } catch (err) {
    res.json({ songs: [] });
  }
});

