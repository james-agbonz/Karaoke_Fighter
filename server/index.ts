// Jobs persistence file
const JOBS_FILE = join(process.cwd(), 'data', 'song-jobs.json');

// Load jobs from file
async function loadJobs(): Promise<Map<string, SongGenerationJob>> {
  try {
    const data = await readFile(JOBS_FILE, 'utf-8');
    const jobs = JSON.parse(data);
    return new Map(Object.entries(jobs));
  } catch {
    return new Map();
  }
}

// Save jobs to file
async function saveJobs(jobs: Map<string, SongGenerationJob>) {
  try {
    await mkdir(join(process.cwd(), 'data'), { recursive: true });
    const obj = Object.fromEntries(jobs);
    await writeFile(JOBS_FILE, JSON.stringify(obj, null, 2));
  } catch (err) {
    console.error('[Jobs] Failed to save:', err);
  }
}

