// Start auto song pack generation
app.post('/api/songs/generate', express.json(), async (req, res) => {
  try {
    const { query, songId } = req.body;
    if (!query || !songId) {
      res.status(400).json({ error: 'query and songId are required' });
      return;
    }

    // Sanitize songId
    const safeId = songId.replace(/[^a-z0-9-]/gi, '').toLowerCase();
    const jobId = `gen_${safeId}_${Date.now()}`;

    const job: SongGenerationJob = {
      id: jobId,
      status: 'pending',
      query,
      songId: safeId,
      progress: 'Initializing...',
      createdAt: Date.now(),
    };
    songJobs.set(jobId, job);
    await saveJobs(songJobs);

    // Start generation in background
    runGenerationJob(jobId, query, safeId).catch(err => {
      console.error(`[Job ${jobId}] Generation failed:`, err);
      const j = songJobs.get(jobId);
      if (j) {
        j.status = 'failed';
        j.error = String(err);
        j.progress = 'Failed';
        j.completedAt = Date.now();
        saveJobs(songJobs);
      }
    });

    res.json({ jobId, status: 'pending' });
  } catch (error) {
    console.error('[API] Generate error:', error);
    res.status(500).json({ error: 'Failed to start generation' });
  }
});

