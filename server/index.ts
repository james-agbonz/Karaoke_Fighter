// Start generating a song pack for the song the user picked.
// Body: { videoId, title, artist?, songId? }   (legacy: { query } = use the first search result)
app.post('/api/songs/generate', express.json(), async (req, res) => {
  try {
    let { videoId, title, artist, songId, query } = req.body || {};
    if (!videoId && query) {
      const results = await runPython('search', [String(query), '1'], { timeoutMs: 45000 });
      if (!results.length) { res.status(404).json({ error: `No songs found for "${query}"` }); return; }
      ({ videoId, title, artist } = results[0]);
    }
    if (!videoId || !VIDEO_ID_RE.test(String(videoId))) { res.status(400).json({ error: 'A valid videoId is required' }); return; }
    title = String(title || videoId).slice(0, 200);
    artist = String(artist || '').slice(0, 200);
    const id = await pickSongId(songId ? String(songId) : `${title}-${artist}`);

    // Same song already queued or running? Reuse that job.
    const active = [...songJobs.values()].find(j => j.songId === id && (j.status === 'pending' || j.status === 'running'));
    if (active) { res.json({ jobId: active.id, status: active.status, songId: id }); return; }

    const job: SongGenerationJob = {
      id: `gen_${id}_${Date.now()}`, status: 'pending', query: query || `${title} ${artist}`.trim(),
      songId: id, videoId, title, artist, progress: 'Waiting to start…', percent: 0, createdAt: Date.now(),
    };
    songJobs.set(job.id, job);
    jobQueue.push(job.id);
    await saveJobs();
    processQueue();
    res.json({ jobId: job.id, status: job.status, songId: id });
  } catch (err: any) {
    console.error('[API] Generate error:', err);
    res.status(500).json({ error: err.message || 'Failed to start generation', hint: err.hint });
  }
});

