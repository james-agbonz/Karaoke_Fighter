interface SongGenerationJob {
  id: string;
  status: 'pending' | 'running' | 'completed' | 'failed';
  query: string;
  songId: string;
  progress: string;
  result?: any;
  error?: string;
  createdAt: number;
  startedAt?: number;
  completedAt?: number;
}

